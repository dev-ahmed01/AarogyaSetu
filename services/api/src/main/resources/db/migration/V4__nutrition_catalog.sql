CREATE TABLE nutrition_sources (
    id              UUID PRIMARY KEY,
    source_code     VARCHAR(80) NOT NULL UNIQUE,
    name            VARCHAR(180) NOT NULL,
    version_label   VARCHAR(80),
    source_type     VARCHAR(40) NOT NULL,
    source_url      VARCHAR(500),
    license_label   VARCHAR(120),
    usage_note      VARCHAR(1000),
    retrieved_on    DATE
);

CREATE TABLE foods (
    id                       UUID PRIMARY KEY,
    slug                     VARCHAR(140) NOT NULL UNIQUE,
    canonical_name           VARCHAR(180) NOT NULL,
    description              VARCHAR(1000),
    food_type                VARCHAR(40) NOT NULL,
    category_code            VARCHAR(50) NOT NULL,
    dietary_classification   VARCHAR(50) NOT NULL,
    primary_region           VARCHAR(80),
    nutrient_status          VARCHAR(50) NOT NULL,
    source_id                UUID REFERENCES nutrition_sources(id),
    source_food_ref          VARCHAR(120),
    active                   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_foods_category ON foods(category_code);
CREATE INDEX idx_foods_dietary ON foods(dietary_classification);
CREATE INDEX idx_foods_region ON foods(primary_region);
CREATE INDEX idx_foods_active ON foods(active);

CREATE TABLE food_aliases (
    food_id       UUID NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    alias         VARCHAR(180) NOT NULL,
    PRIMARY KEY (food_id, alias)
);

CREATE INDEX idx_food_aliases_alias ON food_aliases(alias);

CREATE TABLE food_tags (
    food_id       UUID NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    tag_code      VARCHAR(80) NOT NULL,
    PRIMARY KEY (food_id, tag_code)
);

CREATE TABLE food_allergens (
    food_id        UUID NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    allergen_code  VARCHAR(50) NOT NULL,
    PRIMARY KEY (food_id, allergen_code)
);

CREATE TABLE food_portions (
    id            UUID PRIMARY KEY,
    food_id       UUID NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    label         VARCHAR(100) NOT NULL,
    grams         NUMERIC(8,2) NOT NULL,
    is_default    BOOLEAN NOT NULL DEFAULT FALSE,
    display_order SMALLINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_food_portion_grams CHECK (grams > 0)
);

CREATE INDEX idx_food_portions_food ON food_portions(food_id);

CREATE TABLE food_nutrients (
    id                 UUID PRIMARY KEY,
    food_id            UUID NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    nutrient_code      VARCHAR(60) NOT NULL,
    amount_per_100g    NUMERIC(12,4) NOT NULL,
    unit               VARCHAR(20) NOT NULL,
    source_id          UUID REFERENCES nutrition_sources(id),
    source_food_ref    VARCHAR(120),
    UNIQUE (food_id, nutrient_code),
    CONSTRAINT chk_food_nutrient_amount CHECK (amount_per_100g >= 0)
);

CREATE INDEX idx_food_nutrients_food ON food_nutrients(food_id);
CREATE INDEX idx_food_nutrients_code ON food_nutrients(nutrient_code);

CREATE TABLE food_ingredients (
    parent_food_id      UUID NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    ingredient_food_id  UUID NOT NULL REFERENCES foods(id) ON DELETE RESTRICT,
    quantity_grams      NUMERIC(8,2),
    display_order       SMALLINT NOT NULL DEFAULT 0,
    PRIMARY KEY (parent_food_id, ingredient_food_id),
    CONSTRAINT chk_food_ingredient_not_self CHECK (parent_food_id <> ingredient_food_id),
    CONSTRAINT chk_food_ingredient_grams CHECK (quantity_grams IS NULL OR quantity_grams > 0)
);

